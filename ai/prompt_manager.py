def get_default_prompt(prompt_key: str) -> str:
    return DEFAULT_PROMPTS.get(prompt_key, DEFAULT_PROMPTS["jump_forward"])

def interpolate_prompt(template: str, context: Dict[str, Any]) -> str:
    """Safely replace {VARIABLE} placeholders with context values."""
    def replacer(match):
        key = match.group(1)
        val = context.get(key, None)
        if val is None:
            # Fallback to empty or placeholder
            return match.group(0)
        if isinstance(val, (int, float)):
            return str(val)
        return str(val)
    
    return re.sub(r'\{([A-Za-z0-9_]+)\}', replacer, template)
